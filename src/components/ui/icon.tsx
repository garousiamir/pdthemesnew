export type IconName = keyof typeof map;

export function Icon({ name, ...props }: { name?: string } & LucideProps) {
  const Cmp =
    (name && (map as Record<string, typeof Sparkles>)[name]) || Sparkles;
  return <Cmp aria-hidden {...props} />;
}
